interface LanguageContextValue {
  language: Language;
  toggleLanguage: () => void;
  t: (englishText: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => {
    if (typeof window === "undefined") return "en";
    try {
      return window.localStorage.getItem("wss-language") === "hi" ? "hi" : "en";
    } catch {
      return "en";
    }
  });

  const t = useCallback((englishText: string) => {
    return language === "hi" ? HINDI_TRANSLATIONS[englishText] ?? englishText : englishText;
  }, [language]);

  const toggleLanguage = useCallback(() => {
    const nextLanguage: Language = language === "en" ? "hi" : "en";
    setLanguage(nextLanguage);
    try {
      window.localStorage.setItem("wss-language", nextLanguage);
    } catch {
      // Keep the language toggle usable when browser storage is unavailable.
    }
  }, [language]);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({ language, toggleLanguage, t }), [language, toggleLanguage, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
